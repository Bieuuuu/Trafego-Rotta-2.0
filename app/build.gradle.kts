android {
    namespace = "com.traffigorotta"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.traffigorotta"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables {
            useSupportLibrary = true
        }
    }

    val keystorePropertiesFile = rootProject.file("keystore.properties")
    val hasKeystore = keystorePropertiesFile.exists()

    signingConfigs {
        create("release") {
            if (hasKeystore) {
                val properties = java.util.Properties().apply {
                    keystorePropertiesFile.inputStream().use { load(it) }
                }
                val rawStoreFile = properties.getProperty("storeFile", "release.keystore")
                storeFile = if (rawStoreFile.startsWith("/")) file(rawStoreFile) else rootProject.file(rawStoreFile)
                storePassword = properties.getProperty("storePassword")
                keyAlias = properties.getProperty("keyAlias")
                keyPassword = properties.getProperty("keyPassword")
            } else {
                val envStorePath = System.getenv("KEYSTORE_PATH")
                if (envStorePath != null) {
                    storeFile = file(envStorePath)
                    storePassword = System.getenv("KEYSTORE_PASSWORD")
                    keyAlias = System.getenv("KEY_ALIAS")
                    keyPassword = System.getenv("KEY_PASSWORD")
                }
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            if (hasKeystore || System.getenv("KEYSTORE_PATH") != null) {
                signingConfig = signingConfigs.getByName("release")
            }
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
